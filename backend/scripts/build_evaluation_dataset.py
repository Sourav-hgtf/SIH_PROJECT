"""Build evaluation corpus, gold-standard export, and analyst labeling queue.

Does NOT invent labels. Does NOT train a model.

Usage:
  python3 backend/scripts/build_evaluation_dataset.py
  python3 backend/scripts/build_evaluation_dataset.py --include-labeling-queue
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path

backend_dir = Path(__file__).resolve().parent.parent
project_root = backend_dir.parent
if str(backend_dir) not in sys.path:
    sys.path.insert(0, str(backend_dir))
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from ingestion.dataset_labels import (  # noqa: E402
    LABEL_SOURCE_HUMAN_VALIDATED,
    EvaluationLabelRecord,
)
from ingestion.dataset_quality import (  # noqa: E402
    build_evaluation_corpus,
    load_normalized_as_label_records,
    records_to_jsonl,
    write_validation_report,
)

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(name)s: %(message)s")
logger = logging.getLogger("build_evaluation_dataset")

DEFAULT_INPUT = project_root / "data" / "processed" / "normalized_incidents.json"
DEFAULT_OUT_DIR = project_root / "data" / "processed" / "evaluation"


def write_labeling_queue(challenges: list[EvaluationLabelRecord], path: Path) -> None:
    """Analyst-facing labeling queue with empty label slots."""
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for rec in challenges:
        rows.append(
            {
                "report_id": rec.report_id,
                "report_text": rec.report_text,
                "sif_label": None,
                "label_source": LABEL_SOURCE_HUMAN_VALIDATED,  # target source after labeling
                "labeler_id": None,
                "label_timestamp": None,
                "label_confidence": None,
                "label_comment": None,
                "challenge_category": rec.challenge_category,
                "data_type": rec.data_type,
                "duplicate_group_id": rec.duplicate_group_id,
                "instructions": (
                    "Assign sif_label = true (SIF potential) or false (Non-SIF) per LABELING_GUIDE.md. "
                    "Set labeler_id, label_timestamp (UTC ISO), label_confidence (0-1), "
                    "and label_comment (mandatory rationale). "
                    "Submit via UI LabelReview API for consensus to become gold."
                ),
                "prior_context": rec.metadata,
            }
        )
    path.write_text(json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8")


def write_readme(out_dir: Path, stats: dict) -> None:
    text = f"""# Evaluation Dataset Outputs

Generated by `backend/scripts/build_evaluation_dataset.py`.

## Files

| File | Purpose |
|------|---------|
| `labeled_corpus.jsonl` | Full corpus with Phase-2 label schema + provenance |
| `gold_standard.jsonl` | **Only** `HUMAN_VALIDATED` non-synthetic records (may be empty) |
| `challenge_candidates.jsonl` | Difficult unlabeled cases for analyst review |
| `labeling_queue.json` | Ready-to-label worksheet (empty `sif_label` slots) |
| `dataset_validation_report.json` | Statistics + duplicate pairs + limitations |
| `split_guard_manifest.json` | Duplicate groups that must stay within one split |

## Current snapshot

```json
{json.dumps(stats, indent=2)}
```

## Policy

- Primary gold-standard evaluation uses **only** `label_source = HUMAN_VALIDATED`.
- `SYNTHETIC`, `HEURISTIC`, `IMPORTED`, and `UNKNOWN` are excluded from gold.
- Synthetic records never enter the gold-standard test set.
- See `DATASET_CARD.md` and `LABELING_GUIDE.md` at the repository root.
"""
    (out_dir / "README.md").write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Build SIF evaluation / labeling datasets")
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument("--near-dup-threshold", type=float, default=0.85)
    parser.add_argument(
        "--include-labeling-queue",
        action="store_true",
        default=True,
        help="Write labeling_queue.json for analysts (default: on)",
    )
    parser.add_argument(
        "--no-labeling-queue",
        action="store_true",
        help="Skip labeling_queue.json",
    )
    args = parser.parse_args()

    if not args.input.exists():
        logger.error("Input not found: %s", args.input)
        return 1

    records = load_normalized_as_label_records(args.input)
    corpus, gold, challenges, exact_pairs, near_pairs, stats = build_evaluation_corpus(
        records,
        near_dup_threshold=args.near_dup_threshold,
    )

    args.out_dir.mkdir(parents=True, exist_ok=True)
    records_to_jsonl(corpus, args.out_dir / "labeled_corpus.jsonl")
    records_to_jsonl(gold, args.out_dir / "gold_standard.jsonl")
    records_to_jsonl(challenges, args.out_dir / "challenge_candidates.jsonl")
    write_validation_report(
        stats,
        args.out_dir / "dataset_validation_report.json",
        exact_pairs=exact_pairs,
        near_pairs=near_pairs,
    )

    # Manifest of multi-member duplicate groups for leak-free split enforcement
    groups: dict[str, list[str]] = {}
    for rec in corpus:
        gid = rec.duplicate_group_id or rec.report_id
        groups.setdefault(gid, []).append(rec.report_id)
    multi = {g: ids for g, ids in groups.items() if len(ids) > 1}
    manifest = {
        "policy": "All report_ids in a duplicate_group must share the same train/val/test split.",
        "near_dup_threshold": args.near_dup_threshold,
        "multi_member_groups": multi,
        "group_count": len(multi),
    }
    (args.out_dir / "split_guard_manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    if args.include_labeling_queue and not args.no_labeling_queue:
        write_labeling_queue(challenges, args.out_dir / "labeling_queue.json")

    write_readme(args.out_dir, stats.to_dict())

    logger.info(
        "Built evaluation dataset: total=%d gold=%d synthetic=%d imported=%d challenges=%d",
        stats.total_records,
        stats.usable_gold_standard_records,
        stats.synthetic_records,
        stats.imported_records,
        len(challenges),
    )

    if stats.usable_gold_standard_records == 0:
        logger.warning(
            "Gold-standard set is EMPTY. Collect HUMAN_VALIDATED labels via the labeling "
            "workflow before reporting evaluation metrics. See LABELING_GUIDE.md."
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
